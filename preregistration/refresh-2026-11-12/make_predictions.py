"""Predictions for the refresh paper, written before any new run.

Uses resultbench/model/capacity.py with the CPU costs fitted to every design-A
run of the ResultBench grids (CPU accounting only, no outcome is fitted), and
writes:

- validation-a.csv, validation-m.csv: leave-one-run-out predictions of the existing runs (P1);
- predictions.csv: every predicted configuration;
- predictions-tables.md: the tables quoted in predictions.md.

    cd ~/NoCrashing && source ~/venvs/resultbench/bin/activate
    python refresh-paper/make_predictions.py

On new hardware (the cluster), re-measure the CPU costs first and pass the new
run directories with --runs, so that mu matches that machine.
"""
from __future__ import annotations

import argparse
import csv
import math
import subprocess
import sys
from dataclasses import replace
from pathlib import Path

HERE = Path(__file__).resolve().parent
RB = HERE.parent / "resultbench"
sys.path.insert(0, str(RB))

import yaml  # noqa: E402

from model.capacity import (Room, Surge, Users, cpu_costs, from_scenario, lab_runs, recovery_s,  # noqa: E402
                            room_cpu_costs, simulate, summarize, validate)

CAP_1X = 223.4375  # design A's calibrated capacity in ResultBench (students/s), which defines 1x
DT = 0.1


def run(surge: Surge, users: Users, mu: float, other: float, drain: float, **kw) -> dict:
    r = simulate(surge, users, mu, dt=DT, drain_s=drain, other_cost=other, keep_timeline=True, **kw)
    rec = recovery_s(r.by_send, surge.rise_s)
    return {"served_ok": r.served_ok, "success_5s": r.success_within["5s"], "success_10s": r.success_within["10s"],
            "amplification": r.amplification, "useful_share": r.useful_share,
            "wasted_answers": r.wasted, "completed_answers": r.completed, "recovery_s": rec,
            "overload_outlasts_arrivals": (math.isnan(rec) or rec > surge.post_release_s)}


def fmt(x, pct=False) -> str:
    if isinstance(x, bool):
        return "yes" if x else "no"
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "never"
    return f"{100 * x:.1f}%" if pct else (f"{x:.2f}" if isinstance(x, float) else str(x))


def table(rows: list[dict], keys: list[str], cols: list[tuple[str, str, bool]]) -> str:
    head = "| " + " | ".join(keys + [c[1] for c in cols]) + " |"
    out = [head, "|" + "---|" * (len(keys) + len(cols))]
    for r in rows:
        out.append("| " + " | ".join(str(r[k]) for k in keys) + " | "
                   + " | ".join(fmt(r[c[0]], c[2]) for c in cols) + " |")
    return "\n".join(out)


def write_numbers(path: Path, out: Path, mu: float, ans: float, costs: dict, mu_da: float, rc) -> None:
    """LaTeX macros for every number the paper quotes from the model and its validation."""
    import pandas as pd
    path.parent.mkdir(parents=True, exist_ok=True)
    m = {}

    def mae(df: pd.DataFrame, col: str, scale: float = 100.0) -> tuple[str, str]:
        e = (df[f"obs_{col}"] - df[f"pred_{col}"]).abs().dropna()
        return f"{e.mean() * scale:.1f}", f"{e.max() * scale:.1f}"

    for design, tag in (("a", "A"), ("m", "M")):
        d = pd.read_csv(out / f"validation-{design}.csv")
        m[f"Val{tag}Runs"] = str(len(d))
        for col, name in (("served_ok", "Served"), ("success_5s", "FiveS"), ("useful_share", "Useful")):
            m[f"Val{tag}{name}Mae"], m[f"Val{tag}{name}Max"] = mae(d, col)
        rec = (d.obs_recovery_s - d.pred_recovery_s).abs().dropna()
        m[f"Val{tag}RecMae"] = f"{rec.mean():.1f}"
        m[f"Val{tag}RecRuns"] = str(len(rec))
        m[f"Val{tag}RecAgree"] = str(int((d.obs_recovery_s.isna() == d.pred_recovery_s.isna()).sum()))
    da = pd.read_csv(out / "validation-d-a.csv")
    m["ValDARuns"] = str(len(da))
    m["ValTotalRuns"] = str(sum(int(m[f"Val{t}Runs"]) for t in ("A", "M")) + len(da))
    m["CpuAnswerMs"] = f"{ans * 1000:.2f}"
    m["CpuOtherMs"] = f"{costs['other'] * 1000:.3f}"
    m["CpuIdle"] = f"{costs['idle_cpus']:.3f}"
    m["MuA"] = f"{mu:.0f}"
    m["MuDA"] = f"{mu_da:.0f}"
    m["RoomQueuedUs"] = f"{rc[0] * 1e6:.0f}"
    m["RoomProxiedUs"] = f"{rc[1] * 1e6:.0f}"
    m["AdmitShareOfMu"] = f"{178.8 / mu_da * 100:.0f}"
    lines = ["% Generated by refresh-paper/make_predictions.py. Do not edit."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", type=Path, default=RB / "runs")
    ap.add_argument("--out", type=Path, default=HERE)
    a = ap.parse_args()
    exps = [a.runs / e for e in ("paper-core", "paper-refresh", "paper-wr", "paper-sens")]
    exps = [e for e in exps if e.exists()]
    room_exps = [e for e in (a.runs / "paper-wr", a.runs / "paper-wr-long", a.runs / "paper-refresh") if e.exists()]

    # P1: the existing runs, each predicted without its own measurement.
    md = ["# Predictions (generated)", ""]
    commit = subprocess.run(["git", "-C", str(HERE.parent), "describe", "--always", "--dirty"],
                            capture_output=True, text=True).stdout.strip()
    md += [f"Model code: `resultbench/model/capacity.py` at commit `{commit}`; time step {DT} s.", ""]
    for design, ex in (("a", exps), ("m", [e for e in exps if e.name == "paper-core"]), ("d-a", room_exps)):
        rows = validate(lab_runs(ex, design), DT)
        with (a.out / f"validation-{design}.csv").open("w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(dict.fromkeys(k for r in rows for k in r)))
            w.writeheader()
            w.writerows(rows)
        md += [f"## P1: existing runs of design {design.upper()} (leave one run out)", "", summarize(rows), ""]

    # CPU costs from every design-A run, for the predictions below.
    runs_a = lab_runs(exps, "a")
    costs = cpu_costs(runs_a)
    ans = costs["answer"]["5ms"]
    mu = (1.0 - costs["idle_cpus"]) / ans
    other = costs["other"] / ans
    md += ["## CPU costs used for the predictions", "",
           f"- CPU per answer (PAGE_COST 5 ms): {ans * 1000:.3f} ms",
           f"- CPU per other request: {costs['other'] * 1000:.4f} ms ({other:.4f} answers)",
           f"- constant use per portal: {costs['idle_cpus']:.3f} CPU",
           f"- so design A (1 CPU) finishes mu = {mu:.1f} answers/s; 1x = {CAP_1X} students/s "
           f"(mu / 1x = {mu / CAP_1X:.3f})", ""]

    sc = yaml.safe_load((RB / "bench" / "scenarios" / "paper.yaml").read_text())
    base_surge, base_users = from_scenario(sc)
    impatient = replace(base_users, patience=(3.0, 8.0), retry_prob=0.9, impatient_retry_prob=0.95,
                        retry_delay=(0.5, 2.0))
    no_refresh = replace(base_users, retry_prob=0.0, impatient_retry_prob=0.0)
    all_rows = []

    def surge_at(m: float) -> Surge:
        return replace(base_surge, peak=m * CAP_1X)

    # P2: load x patience -> does the overload outlast the arrivals? (longer runs: 240 s after arrivals stop)
    p2 = []
    for lo, hi in ((3, 8), (5, 20), (10, 30)):
        for m in (1.0, 1.25, 1.5, 2.0, 2.5, 3.0, 4.0, 5.0):
            u = replace(base_users, patience=(float(lo), float(hi)))
            r = {"block": "P2", "patience_s": f"{lo}-{hi}", "load": f"{m:g}x", **run(surge_at(m), u, mu, other, 240)}
            p2.append(r)
    all_rows += p2
    md += ["## P2: tipping point (default refreshing: 0.8 after an error, 0.9 after a time-out, pause 1-5 s; "
           "runs end 240 s after arrivals stop)", "",
           table(p2, ["patience_s", "load"], [("served_ok", "served", True), ("success_5s", "within 5 s", True),
                                              ("useful_share", "useful work", True), ("amplification", "requests/student", False),
                                              ("recovery_s", "recovery (s)", False),
                                              ("overload_outlasts_arrivals", "overload outlasts arrivals (90 s)", False)]), ""]

    # P3: recovery time against refresh probability, at 2x and 5-20 s patience.
    p3 = []
    for p in (0.0, 0.5, 0.7, 0.8, 0.9, 0.95):
        u = replace(base_users, retry_prob=p, impatient_retry_prob=p)
        p3.append({"block": "P3", "refresh_prob": p, "load": "2x", **run(surge_at(2.0), u, mu, other, 240)})
    all_rows += p3
    md += ["## P3: recovery against refresh probability (2x, patience 5-20 s, same probability after errors and "
           "time-outs; runs end 240 s after arrivals stop)", "",
           table(p3, ["refresh_prob", "load"], [("served_ok", "served", True), ("useful_share", "useful work", True),
                                                ("amplification", "requests/student", False),
                                                ("recovery_s", "recovery (s)", False)]), ""]

    # P4: queue length and order. (In rb portal MAX_QUEUE=0 means no limit, so 0 is not a test point.)
    p4 = []
    for name, users, m in (("default", base_users, 2.0), ("impatient", impatient, 2.0), ("default", base_users, 5.0)):
        for cap in (4096, 1100, 256):
            for order in ("fifo", "lifo"):
                p4.append({"block": "P4", "students": name, "load": f"{m:g}x", "queue": cap, "order": order,
                           **run(surge_at(m), users, mu, other, 45, queue_cap=cap, order=order)})
    all_rows += p4
    md += ["## P4: queue length and order (paper scenario, runs end 45 s after arrivals stop)", "",
           table(p4, ["students", "load", "queue", "order"],
                 [("served_ok", "served", True), ("success_5s", "within 5 s", True), ("useful_share", "useful work", True),
                  ("amplification", "requests/student", False), ("recovery_s", "recovery (s)", False)]), ""]

    # P5: waiting room in front of A (D-A: portal 0.875 CPU, room 0.25 CPU), token tickets.
    runs_da = lab_runs(room_exps, "d-a")
    costs_da = cpu_costs(runs_da)
    rc = room_cpu_costs(runs_da)
    ans_da = costs_da["answer"]["5ms"]
    mu_da = (0.875 - costs_da["idle_cpus"]) / ans_da
    other_da = costs_da["other"] / ans_da
    md += ["## CPU costs for the waiting-room predictions", "",
           f"- design A behind the room (0.875 CPU): mu = {mu_da:.1f} answers/s",
           f"- room (0.25 CPU): {rc[0] * 1e6:.1f} us per queued answer, {rc[1] * 1e6:.1f} us per passed-through request",
           f"- ResultBench admitted 178.8 students/s (80% of A's 223.4 at 1 CPU) = {178.8 / mu_da:.0%} of mu", ""]
    p5 = []
    variants = [("as run (ResultBench)", 178.8, 0), ("admit 80% of mu", 0.8 * mu_da, 0),
                ("cap 2 server requests", 178.8, 2), ("80% of mu and cap 2", 0.8 * mu_da, 2)]
    for name, users_v, m in (("default", base_users, 5.0), ("impatient", impatient, 2.0)):
        for label, rate, cap in variants:
            room = Room(admit_rate=rate, mode="token", cpus=0.25, cost_queued=rc[0], cost_proxied=rc[1],
                        request_cap=cap)
            r = simulate(surge_at(m), users_v, mu_da, dt=DT, drain_s=45, other_cost=other_da, room=room)
            p5.append({"block": "P5", "students": name, "load": f"{m:g}x", "room": label,
                       "admit_per_s": round(rate, 1), "served_ok": r.served_ok,
                       "success_10s": r.success_within["10s"], "useful_share": r.useful_share,
                       "backend_amplification": r.backend_amplification, "wait_p50_s": r.wait_p50_s})
    all_rows += p5
    md += ["## P5: waiting room with token tickets (runs end 45 s after arrivals stop). "
           "The model over-predicts 'served' for token rooms (see P1, design D-A).", "",
           table(p5, ["students", "load", "room", "admit_per_s"],
                 [("served_ok", "served", True), ("success_10s", "within 10 s", True),
                  ("useful_share", "useful work", True),
                  ("backend_amplification", "server requests/student", False),
                  ("wait_p50_s", "median wait (s)", False)]), ""]

    # P6: stop work when the student leaves (CANCEL_ON_DISCONNECT=true).
    p6 = []
    for name, users, m in (("no refresh", no_refresh, 2.0), ("default", base_users, 2.0),
                           ("impatient", impatient, 2.0), ("default", base_users, 5.0)):
        for cancel in (False, True):
            p6.append({"block": "P6", "students": name, "load": f"{m:g}x", "cancel_on_disconnect": cancel,
                       **run(surge_at(m), users, mu, other, 45, cancel_on_disconnect=cancel)})
    all_rows += p6
    md += ["## P6: stop the work when the student leaves", "",
           table(p6, ["students", "load", "cancel_on_disconnect"],
                 [("served_ok", "served", True), ("success_5s", "within 5 s", True), ("useful_share", "useful work", True),
                  ("recovery_s", "recovery (s)", False)]), ""]

    # P7: mirrors with half the CPU each: 256 workers (as run) or 128.
    p7 = []
    for m in (5.0, 10.0):
        for workers in (256, 128):
            s = replace(surge_at(m), peak=m * CAP_1X / 2)
            mu_m = (0.5 - costs["idle_cpus"]) / ans
            p7.append({"block": "P7", "load": f"{m:g}x", "workers_per_mirror": workers,
                       **run(s, no_refresh, mu_m, other, 45, workers=workers)})
    all_rows += p7
    md += ["## P7: two mirrors with 0.5 CPU each, students do not refresh (as paper-core M)", "",
           table(p7, ["load", "workers_per_mirror"], [("served_ok", "served", True), ("success_5s", "within 5 s", True),
                                                       ("useful_share", "useful work", True)]), ""]

    write_numbers(a.out / "paper" / "generated" / "numbers.tex", a.out, mu, ans, costs, mu_da, rc)

    keys = sorted({k for r in all_rows for k in r})
    with (a.out / "predictions.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        w.writerows(all_rows)
    (a.out / "predictions-tables.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
